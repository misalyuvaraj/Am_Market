const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem("am-lang") || "en";
    } catch {
      return "en";
    }
  });

  function setLang(next) {
    setLangState(next);
    try {
      localStorage.setItem("am-lang", next);
    } catch {
      /* ignore */
    }
  }

  useEffect(() => {
    document.documentElement.lang = lang === "hi" ? "hi" : lang === "mr" ? "mr" : "en";
  }, [lang]);

  const t = useMemo(() => {
    const table = dict[lang] || dict.en;
    return (key) => table[key] || dict.en[key] || key;
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t, langs: LANGS }), [lang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang needs LangProvider");
  return ctx;
}

export function useT() {
  return useLang().t;
}

export function LanguageSelect() {
  const { lang, setLang, langs, t } = useLang();
  const [open, setOpen] = useState(false);
  const box = useRef(null);
  const cur = langs.find((l) => l.id === lang) || langs[0];

  useEffect(() => {
    function close(e) {
      if (!box.current?.contains(e.target)) setOpen(false);
    }
    document.addEventListener("mousedown", close);
    return () => document.removeEventListener("mousedown", close);
  }, []);

  return (
    <div className="lang-wrap" ref={box}>
      <button className="lang-btn" type="button" onClick={() => setOpen((v) => !v)} title={t("lang.label")}>
        <Languages size={15} />
        <span>{cur.short}</span>
        <span className="lang-native">{cur.native}</span>
      </button>
      {open ? (
        <div className="lang-menu">
          {langs.map((l) => (
            <button
              key={l.id}
              type="button"
              className={l.id === lang ? "on" : ""}
              onClick={() => {
                setLang(l.id);
                setOpen(false);
              }}
            >
              <b>{l.short}</b>
              <span>{l.native}</span>
            </button>
          ))}
        </div>
      ) : null}
    </div>
  );
}
